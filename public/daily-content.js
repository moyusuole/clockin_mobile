  // FNV-1a 字符串散列 → 32 位无符号整数
  function hashSeed(str) {
    var h = 2166136261 >>> 0;
    for (var i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = Math.imul(h, 16777619) >>> 0;
    }
    return h >>> 0;
  }

  function mulberry32(a) {
    return function () {
      a = (a + 0x6D2B79F5) >>> 0;
      var t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  // 确定性洗牌：同一种子必得同一顺序
  function shuffled(pool, seed) {
    var arr = pool.slice();
    var rnd = mulberry32(seed);
    for (var i = arr.length - 1; i > 0; i--) {
      var j = Math.floor(rnd() * (i + 1));
      var tmp = arr[i]; arr[i] = arr[j]; arr[j] = tmp;
    }
    return arr;
  }

  function takeCyclic(arr, startIdx, n) {
    var out = [];
    var len = arr.length;
    if (!len) return out;
    startIdx = ((startIdx % len) + len) % len;
    for (var i = 0; i < n && i < len; i++) out.push(arr[(startIdx + i) % len]);
    return out;
  }

  /**
   * 抽取：
   * @param {string} dateStr 'YYYY-MM-DD' —— 决定当天基准洗牌顺序
   * @param {string} type 'fact' | 'quote'
   * @param {number} offset 手动刷新次数（0 = 当天自动刷新的那两条）
   * @param {number} n 每次取几条
   */
  function draw(dateStr, type, offset, n) {
    var pool = (type === 'quote') ? QUOTES : FACTS;
    var seq = shuffled(pool, hashSeed(type + '|' + String(dateStr)));
    return takeCyclic(seq, (Number(offset) || 0) * n, n);
  }

